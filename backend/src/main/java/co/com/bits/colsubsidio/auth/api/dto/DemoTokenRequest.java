package co.com.bits.colsubsidio.auth.api.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

/**
 * Credentials exchanged for a demonstration token.
 *
 * <p>The record is the only place in the prototype where a password travels in clear text, and it does
 * so over the TLS channel of the request and for the lifetime of a single call. It is never logged, never
 * copied into an audit entry and never returned to the client: the service hashes the value it receives
 * and compares it against the stored BCrypt digest, so the plain value dies with the request.</p>
 *
 * <p>Validation happens at the boundary before the service is invoked. An empty username or a password
 * outside the accepted length range produces a {@code 400} problem detail generated by the central
 * exception handler, which means the authentication code only ever sees well formed input and can keep
 * its single responsibility.</p>
 *
 * @param username demonstration account identifier; must match an enabled row in {@code app_user}
 * @param password plain credential supplied by the caller; it is compared with the stored hash and is
 *                 never persisted, logged or echoed back in the response
 * @author Manuela Cortés Granados (manuelacortesgranados@gmail)
 * @since 2026-10-20 11:42 GMT-5 Bogotá D.C. Colombia
 */
public record DemoTokenRequest(
        @NotBlank(message = "username is required")
        @Size(max = 60, message = "username must not exceed 60 characters")
        String username,

        @NotBlank(message = "password is required")
        @Size(min = 8, max = 72, message = "password must be between 8 and 72 characters")
        String password) {
}
